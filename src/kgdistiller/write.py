"""The knowledge write path: list and ``accept`` drafts, generate source ``sheet``s and ``harvest`` them, then index and embed the created records.

Drafts are proposed new records in ``<root>/.knowledge/drafts/``. ``drafts``
reads them from files with what ``accept`` would make of each, writing
nothing. ``accept`` validates them in the post-acceptance world under the home
lock and moves each into ``entries/`` with ``os.link`` then ``os.unlink``, so an
accepted record is never overwritten. A sheet is a generated view of one
source's records and drafts; the only state read back from it is the checkbox
of each draft row.
"""

