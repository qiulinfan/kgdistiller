from __future__ import annotations

import runpy
import unittest
from pathlib import Path, PurePosixPath


REPO_ROOT = Path(__file__).resolve().parents[1]
CHECKER = runpy.run_path(str(REPO_ROOT / "scripts" / "check_distribution.py"))


class DistributionInventoryTest(unittest.TestCase):
    def test_distribution_inventory_ignores_python_bytecode_caches(self) -> None:
        product_cache = (
            REPO_ROOT
            / "skills"
            / "extract-paper-markdown"
            / "scripts"
            / "__pycache__"
        )
        package_cache = REPO_ROOT / "src" / "kgdistiller" / "static" / "__pycache__"
        product_probe = product_cache / "distribution-regression.cpython-313.pyc"
        package_probe = package_cache / "distribution-regression.cpython-313.pyc"
        for cache, probe in (
            (product_cache, product_probe),
            (package_cache, package_probe),
        ):
            cache.mkdir(exist_ok=True)
            probe.write_bytes(b"generated bytecode probe")
        try:
            package = CHECKER["_expected_package_files"]()
            wheel, sdist = CHECKER["_expected_product_files"]()
        finally:
            for cache, probe in (
                (product_cache, product_probe),
                (package_cache, package_probe),
            ):
                probe.unlink(missing_ok=True)
                try:
                    cache.rmdir()
                except OSError:
                    pass

        wheel_path = PurePosixPath(
            "kgdistiller/product/skills/extract-paper-markdown/scripts/"
            "__pycache__/distribution-regression.cpython-313.pyc"
        ).as_posix()
        source_path = PurePosixPath(
            "skills/extract-paper-markdown/scripts/__pycache__/"
            "distribution-regression.cpython-313.pyc"
        ).as_posix()
        package_path = PurePosixPath(
            "kgdistiller/static/__pycache__/"
            "distribution-regression.cpython-313.pyc"
        ).as_posix()
        self.assertNotIn(package_path, package)
        self.assertNotIn(wheel_path, wheel)
        self.assertNotIn(source_path, sdist)


if __name__ == "__main__":
    unittest.main()
