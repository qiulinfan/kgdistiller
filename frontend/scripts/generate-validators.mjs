import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "../..");
const schemaRoot = path.join(repositoryRoot, "src/kgdistiller/schemas");
const outputRoot = path.join(repositoryRoot, "frontend/src/api");
const inputs = [
  ["apiResponse", "qlkg-api-response-v1.schema.json"],
  ["apiError", "qlkg-api-error-v1.schema.json"],
  ["recallRequest", "qlkg-recall-request-v1.schema.json"]
];

function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

const ajv = new Ajv2020({
  allErrors: false,
  code: { esm: true, source: true },
  strict: true,
  strictTypes: false,
  validateFormats: false
});
const exports = {};
const sourceDigests = {};
for (const [exportName, filename] of inputs) {
  const raw = await readFile(path.join(schemaRoot, filename), "utf8");
  const schema = JSON.parse(raw);
  delete schema.$schema;
  schema.$id = `urn:kgdistiller:${exportName}`;
  ajv.addSchema(schema, schema.$id);
  exports[exportName] = schema.$id;
  sourceDigests[filename] = createHash("sha256").update(canonical(schema)).digest("hex");
}

const banner = `// Generated by scripts/generate-validators.mjs.\n// Sources: ${canonical(sourceDigests)}\n`;
const moduleCode = `${banner}${standaloneCode(ajv, exports)}`;
await mkdir(outputRoot, { recursive: true });
await writeFile(path.join(outputRoot, "validators.generated.js"), moduleCode, "utf8");
await writeFile(
  path.join(outputRoot, "validators.generated.d.ts"),
  [
    "export interface ValidationError { instancePath: string; schemaPath: string; keyword: string; message?: string; }",
    "export interface Validator { (value: unknown): boolean; errors?: ValidationError[] | null; }",
    "export const apiResponse: Validator;",
    "export const apiError: Validator;",
    "export const recallRequest: Validator;",
    ""
  ].join("\n"),
  "utf8"
);
